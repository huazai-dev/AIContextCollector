const MOODS = ['紧张', '平静', '压抑', '温暖', '凌厉', '悬疑', '怅然', '激昂', '温柔', '肃杀'];

/* ---------------- 主入口 ---------------- */
function generateScript({ theme, characters, shotCount, styleId }) {
  const seed = hashStr(`${theme}|${JSON.stringify(characters)}|${styleId}`);
  const rng = mulberry32(seed);
  const genre = detectGenre(theme, styleId);
  const kw = keywordOf(theme);

  // 角色整理：第一个 = 主角 A，第二个 = 对手/搭档 B；不足则自动补角
  const chars = (characters || []).filter(c => c && (c.name || '').trim());
  const norm = (c, fallbackName) => ({
    name: (c.name || fallbackName).trim().slice(0, 8),
    role: (c.role || '').trim().slice(0, 12),
    personality: (c.personality || '').trim().slice(0, 20),
    goal: (c.goal || '').trim().slice(0, 20),
  });
  const FALLBACK_B = {
    nixi: [['顾怀远', '集团继承人'], ['陆景行', '隐世家族掌舵人']],
    xuanyi: [['沈默', '刑警队长'], ['周砚', '刑侦顾问']],
    tianchong: [['陆时衍', '集团总裁'], ['顾淮安', '新锐设计师']],
    fuchou: [['霍庭深', '商界巨鳄'], ['秦暮寒', '豪门掌权者']],
    dushi: [['周野', '合伙人'], ['陈一帆', '竞争对手']],
    gufeng: [['谢听澜', '剑宗传人'], ['燕归尘', '江湖客']],
    wenqing: [['林秋声', '儿时旧友'], ['许知夏', '邻家长辈']],
  };
  const A = norm(chars[0] || { name: '陈默' }, '陈默');
  const fallbacks = FALLBACK_B[genre.id] || [['沈砚', '神秘来客'], ['江临风', '神秘来客']];
  let fb = fallbacks.find(([n]) => n !== A.name) || fallbacks[0];
  const [fbName, fbRole] = fb;
  const B = norm(chars[1] || {}, fbName);
  if (!chars[1]) { B.role = B.role || fbRole; }
  if (!A.role) A.role = genre.id === 'tianchong' ? '都市白领' : '普通人';
  const fill = s => s.replaceAll('{A}', A.name).replaceAll('{B}', B.name).replaceAll('{kw}', kw);
  const pickFor = (bank, name, extra) => {
    if (bank[name] && bank[name].length) return pick(rng, bank[name]);
    return fill(pick(rng, bank.default));
  };

  // 剧名 / 简介
  const title = pick(rng, TITLES[genre.id]).replaceAll('{kw}', kw);
  const logline = fill(pick(rng, LOGLINES[genre.id]));

  // 分幕
  const nActs = shotCount >= 4 ? 4 : 3;
  const actDefs = ACTS[genre.id].slice(0, nActs);
  const dist = shotCount >= 4 ? [0.3, 0.25, 0.3, 0.15] : [0.35, 0.35, 0.3];
  const actShots = [];
  let acc = 0;
  for (let a = 0; a < nActs; a++) {
    const n = a === nActs - 1 ? shotCount - acc : Math.max(1, Math.round(shotCount * dist[a]));
    actShots.push(n); acc += n;
  }
  while (acc < shotCount) { actShots[0]++; acc++; }
  while (acc > shotCount) { const i = actShots.length - 1; if (actShots[i] > 1) actShots[i]--; else actShots[0]--; acc--; }
  const acts = actDefs.map((d, i) => ({ act: i + 1, label: ['开端', '推进', '高潮', '结局'][i] || `第${i + 1}幕`, summary: fill(d), shots: actShots[i] }));

  // 场景库 + 逐镜
  const scenePool = genre.scenes.concat(GENERIC_SCENES);
  const scenes = pickN(rng, scenePool, shotCount);
  const shots = [];
  let gi = 0;
  for (let a = 0; a < acts.length; a++) {
    for (let s = 0; s < acts[a].shots; s++) {
      const idx = shots.length;
      const isClimax = a === nActs - 1 || (a === nActs - 2 && s === acts[a].shots - 1);
      const isOpening = idx === 0;
      const scene = scenes[idx];
      const action = fill(pick(rng, genre.actions));
      const camera = pick(rng, CAMERAS);
      const duration = isClimax ? 7 + Math.floor(rng() * 2) : isOpening ? 4 : 5 + Math.floor(rng() * 3);
      const hasLine = !(idx === 0 && rng() < 0.5) && rng() < 0.75;
      const [speaker, line] = hasLine ? pick(rng, genre.lines) : [null, null];
      shots.push({
        index: idx + 1,
        act: a + 1,
        actLabel: acts[a].label,
        scene,
        action,
        camera,
        dialogue: line ? fill(line) : '',
        speaker: speaker ? fill(speaker) : '',
        duration,
        mood: pick(rng, MOODS),
      });
      gi++;
    }
  }

  // 梗概
  const synopsis =
    `${logline}${A.role ? `主人公${A.name}${A.personality ? `性格${A.personality}` : ''}，` : ''}` +
    `全片共 ${shotCount} 个分镜，分为${acts.map(x => x.label).join('、')}${nActs} 幕。` +
    acts.map(x => `${x.label}：${x.summary}。`).join('') +
    (B.name !== A.name ? `${B.name}${B.role ? `（${B.role}）` : ''}在剧中与${A.name}针锋相对，推动剧情层层升级。` : '');

  const charCards = [
    { name: A.name, role: A.role, personality: A.personality, goal: A.goal, tag: '主角' },
    { name: B.name, role: B.role, personality: B.personality, goal: B.goal, tag: '关键角色' },
  ];

  return {
    seed, genreId: genre.id, genreName: genre.name, title, logline, synopsis, acts, shots, characters: charCards,
  };
}

module.exports = { generateScript };
