function keywordOf(theme) {
  const t = (theme || '').replace(/[，。！？、；：,.!?;:'"“”‘’（）()\s]/g, '');
  // 优先取题材关键词（全主题扫描）
  for (const g of GENRES) for (const k of g.kw) if (t.includes(k)) return k;
  // 去掉常见虚词后取尾部 2-6 字作为关键词（更接近标题感）
  const stripped = t.replace(/[的了在从把被着是与个一就都还也很会要想到去来着这那自己因为所以但是只是没有可以已经从此谁他她它你们]/g, '');
  if (stripped) return stripped.slice(-Math.min(6, stripped.length));
  return t.slice(-6) || '命运';
}
function detectGenre(theme, styleId) {
  const t = (theme || '').toLowerCase();
  let best = null, bestLen = 0;
  for (const g of GENRES) {
    for (const k of g.kw) {
      if (t.includes(k) && k.length > bestLen) { best = g; bestLen = k.length; }
    }
  }
  if (!best) {
    if (styleId === 'xianxia') best = GENRES.find(g => g.id === 'gufeng');
    else if (styleId === 'noir' || styleId === 'thriller') best = GENRES.find(g => g.id === 'xuanyi');
    else best = GENRES.find(g => g.id === 'dushi');
  }
  return best;
}

